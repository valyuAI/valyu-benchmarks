def call_queryts_api(question, tool_choice='valyu'):
  """
  Call query.ts TypeScript system directly via subprocess to generate a response.
  Uses the same pattern as queryts.py but contained entirely within this script.
  """
  try:
    print(f"🔍 Querying with TypeScript query.ts: {question}")
    print(f"🔧 Using tool: {tool_choice}")

    # Use subprocess call with retry logic
    max_retries = 3

    for attempt in range(max_retries + 1):
      try:
        print(f"🔄 Attempt {attempt + 1}/{max_retries + 1}")

        # Add a small delay between retries (except for first attempt)
        if attempt > 0:
            time.sleep(2)

        # Prepare the command to call query.ts
        cmd = [
            'npx', 'tsx',
            'query.ts',
            '--benchmark',
            '--question', question,
            '--tool', tool_choice
        ]

        # Set up environment variables for Vertex AI
        env = os.environ.copy()
        env['GOOGLE_VERTEX_LOCATION'] = os.getenv('GOOGLE_CLOUD_LOCATION', 'us-central1')
        env['GOOGLE_VERTEX_PROJECT'] = os.getenv('GOOGLE_CLOUD_PROJECT', 'your-gcp-project')

        # Execute the subprocess
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=300,  # 5 minute timeout
            env=env,
            cwd='.'
        )

        # Check for errors
        if result.returncode != 0:
            error_msg = result.stderr.strip() if result.stderr else "Unknown error"
            print(f"❌ Query.ts script failed with return code {result.returncode}: {error_msg}")
            if attempt == max_retries:  # Last attempt
                return f"Error: Query.ts script failed: {error_msg}"
            continue  # Try next attempt

        # Display stderr output for debugging (includes console.error from Node.js)
        if result.stderr:
            stderr_output = result.stderr.strip()
            if stderr_output:
                print(f"[Query.ts Debug] {stderr_output}")

        # Get the response from stdout
        response = result.stdout.strip()

        if not response:
            error_msg = result.stderr.strip() if result.stderr else "No response received"
            print(f"⚠️ Empty response from Query.ts: {error_msg}")
            if attempt == max_retries:  # Last attempt
                return f"Error: No response received from Query.ts: {error_msg}"
            continue  # Try next attempt

        # Parse JSON response to extract text (from queryts.py pattern)
        try:
            parsed_response = json.loads(response)
            text_response = parsed_response.get('text', '')
            tool_outputs = parsed_response.get('toolOutputs', [])
            message_count = parsed_response.get('messageCount', 0)

            print(f"✅ Successfully got response on attempt {attempt + 1} ({len(text_response)} chars, {len(tool_outputs)} tools, {message_count} messages)")
            return text_response

        except json.JSONDecodeError as e:
            print(f"⚠️ Failed to parse JSON response, treating as plain text: {e}")
            # Fallback to treating response as plain text
            return response

      except subprocess.TimeoutExpired:
        print(f"❌ Query.ts script timed out after 300 seconds on attempt {attempt + 1}")
        if attempt == max_retries:  # Last attempt
            return "Error: Query.ts script timeout (300s)"
        continue  # Try next attempt

      except Exception as e:
        print(f"❌ Attempt {attempt + 1} failed with error: {str(e)}")
        if attempt == max_retries:  # Last attempt
            return f"Error retrieving information after all retry attempts: {str(e)}"
        continue  # Try next attempt

    # This should never be reached, but adding as safety
    return "Failed to generate response after all retry attempts"

  except Exception as e:
    print(f"❌ Error in call_queryts_api: {str(e)}")
    return f"Error processing query: {str(e)}"

